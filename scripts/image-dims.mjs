// Writes lib/image-dims.ts: the width and height of every photo in public/images (floor plans are left out), so a
// photo's `sizes` can be worked out from its own proportions (lib/image-sizes.ts). Run it after adding or replacing a
// photo:  npm run image-dims
// It reads only the file headers (JPEG, PNG, WebP), with no dependency.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = join(process.cwd(), "public");
const start = join(root, "images");

function jpeg(buf) {
  let i = 2;
  while (i < buf.length) {
    if (buf[i] !== 0xff) return null;
    const marker = buf[i + 1];
    const length = buf.readUInt16BE(i + 2);
    // SOF0–SOF15, except DHT (C4), JPG (C8) and DAC (CC)
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
      return { h: buf.readUInt16BE(i + 5), w: buf.readUInt16BE(i + 7) };
    }
    i += 2 + length;
  }
  return null;
}

function png(buf) {
  return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
}

function webp(buf) {
  const kind = buf.toString("ascii", 12, 16);
  if (kind === "VP8 ") return { w: buf.readUInt16LE(26) & 0x3fff, h: buf.readUInt16LE(28) & 0x3fff };
  if (kind === "VP8L") {
    const b = buf.readUInt32LE(21);
    return { w: (b & 0x3fff) + 1, h: ((b >> 14) & 0x3fff) + 1 };
  }
  if (kind === "VP8X") return { w: buf.readUIntLE(24, 3) + 1, h: buf.readUIntLE(27, 3) + 1 };
  return null;
}

function size(file) {
  const buf = readFileSync(file);
  if (buf[0] === 0xff && buf[1] === 0xd8) return jpeg(buf);
  if (buf.toString("ascii", 1, 4) === "PNG") return png(buf);
  if (buf.toString("ascii", 0, 4) === "RIFF" && buf.toString("ascii", 8, 12) === "WEBP") return webp(buf);
  return null;
}

function walk(dir, out) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      if (name !== "floorplans") walk(full, out);
    } else if (/\.(jpe?g|png|webp)$/i.test(name)) {
      const s = size(full);
      if (s) out.push(["/" + relative(root, full).split(sep).join("/"), s.w, s.h]);
    }
  }
  return out;
}

const rows = walk(start, []).sort((a, b) => a[0].localeCompare(b[0]));
const body = rows.map(([src, w, h]) => `  "${src}": [${w}, ${h}],`).join("\n");
writeFileSync(
  join(process.cwd(), "lib", "image-dims.ts"),
  `// Generated by scripts/image-dims.mjs (npm run image-dims): width and height of every photo in public/images.\n` +
    `export const IMAGE_DIMS: Record<string, readonly [number, number]> = {\n${body}\n};\n`
);
console.log(`lib/image-dims.ts: ${rows.length} photos`);
